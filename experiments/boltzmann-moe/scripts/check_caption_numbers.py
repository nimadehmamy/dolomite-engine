#!/usr/bin/env python3
"""Flag numbers asserted in a table's CAPTION that no longer appear in its generated body.

WHY (2026-09-22). tab:main's body is generated by gen_table1.py; its caption is hand-written and
quotes specific values from that body ("48.24 vs 47.29", "FLOPwt 301.0 vs 299.4M", the 0.95pp and
1.91pp gaps). Adding a row re-derives the body and can move the per-group \\mathbf bolding, but
nothing re-derives the caption -- so a stale caption number survives every check that only looks at
LaTeX validity. This script compares the two.

It is deliberately noisy-but-cheap: it reports every caption number missing from the body, INCLUDING
derived quantities (differences like 0.95, percentages, seed spreads) that are legitimately absent.
Read it as "justify each of these", not as "each of these is a bug".

Usage: python scripts/check_caption_numbers.py <tex> <label>
"""
import re, sys

tex, label = sys.argv[1], sys.argv[2]
s = open(tex).read()

i = s.find('\\label{' + label + '}')
if i < 0:
    sys.exit(f"label {label} not found in {tex}")
# the table environment containing the label
b = s.rfind('\\begin{table', 0, i)
e = s.find('\\end{table}', i)
env = s[b:e]

cap_m = re.search(r'\\caption\{', env)
if not cap_m:
    sys.exit("no \\caption in that table environment")
# brace-match the caption
j = cap_m.end(); depth = 1
while j < len(env) and depth:
    if env[j] == '{' and env[j-1] != '\\': depth += 1
    elif env[j] == '}' and env[j-1] != '\\': depth -= 1
    j += 1
caption = env[cap_m.end():j-1]
body = env[:cap_m.start()] + env[j:]

num = lambda t: set(re.findall(r'\d+\.\d+|\d{2,}', t))
cap_n, body_n = num(caption), num(body)
missing = sorted(cap_n - body_n, key=lambda x: (-len(x), x))

print(f"  caption numbers: {len(cap_n)}   body numbers: {len(body_n)}")
print(f"  in caption but NOT in body ({len(missing)}) -- each needs a reason:")
for m in missing:
    ctx = re.search(r'.{0,55}' + re.escape(m) + r'.{0,25}', caption, re.S)
    print(f"    {m:>10s}  ...{' '.join(ctx.group(0).split()) if ctx else ''}...")

# which row currently carries the per-group bold, so a caption claiming a leader can be checked
print("  rows carrying \\mathbf (the per-group maxima the script chose):")
for line in body.split('\n'):
    if '\\mathbf' in line and '&' in line:
        print(f"    {line.split('&')[0].strip():44s} {re.search(r'mathbf\{+([0-9.]+)', line).group(1)}")
