#!/usr/bin/env python3
"""Splice a table generator's output into a .tex file, in place, safely.

WHY THIS EXISTS (2026-09-22). Regenerating a table by hand once deleted the
`\\resizebox{\\textwidth}{!}{%` line sitting ABOVE the `% GENERATED` marker, leaving an
unmatched `}`. pdflatex cannot run here (eso-pic.sty missing), so that was discoverable only
on Overleaf.

FIRST VERSION OF THIS SCRIPT MADE A WORSE MISTAKE and is the reason for the caption guard
below. It assumed the generated block ran from the marker to the line before `\\end{table}`.
In sec/experiments.tex the `\\caption` and `\\label` sit AFTER the tabular, so that region
included them and the splice DELETED the caption and the label. Braces still balanced and the
environment counts still matched, so every check passed. Only a diff caught it.

The generators (gen_table1.py, gen_status_table.py) emit exactly:
    % GENERATED by ...
    % Regenerate ...
    [% omitted: ...]
    \\resizebox{\\textwidth}{!}{%
    \\begin{tabular}{...} ... \\end{tabular}%
    }
so they own the resizebox and NOTHING else. The region to replace therefore ends at the bare
`}` that closes that resizebox -- found as the first `}`-only line after the `\\end{tabular}`
that follows the marker -- never at `\\end{table}`.

Refuses to write if: the marker is not unique; the generator's first line lacks the marker or
its last line is not a bare `}`; the region to be replaced contains `\\caption` or `\\label`;
or the result has unbalanced braces or mismatched table/tabular environments.

Usage:
  python scripts/splice_generated_table.py <tex> <marker-substring> -- <generator cmd...>
"""
import re, subprocess, sys, os

REPO_EXP = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

def balanced(s):
    t = re.sub(r'\\[{}]', '', s)
    return t.count('{') == t.count('}'), t.count('{'), t.count('}')

def main():
    if '--' not in sys.argv:
        sys.exit(__doc__)
    i = sys.argv.index('--')
    tex, marker = sys.argv[1], sys.argv[2]
    cmd = sys.argv[i+1:]

    r = subprocess.run(cmd, capture_output=True, text=True, cwd=REPO_EXP)
    if r.returncode != 0:
        sys.exit(f"generator failed ({r.returncode}):\n{r.stderr[-2000:]}")
    block = r.stdout.rstrip('\n').split('\n')
    while block and not block[0].lstrip().startswith('%'):
        block.pop(0)                                   # drop torch/CUDA stdout noise
    if not block or marker not in block[0]:
        sys.exit(f"generator's first line lacks marker {marker!r}: {block[:1]}")
    # TWO GENERATOR SHAPES, and the difference is exactly what broke this paper before.
    #   A (gen_table1.py):       marker, [% omitted], \resizebox{..}{%, tabular, \end{tabular}%, }
    #     -> the generator OWNS the resizebox; replace [marker .. the bare '}'].
    #   B (gen_status_table.py): marker, tabular, ..., \end{tabular}
    #     -> the FILE owns the resizebox, on the line between the marker and the tabular.
    #        Replacing from the marker would DELETE it and leave an unmatched '}' -- that is the
    #        original Table 6 breakage. So for B, replace only [\begin{tabular} .. \end{tabular}]
    #        and leave the marker and the resizebox untouched.
    if block[-1].strip() == '}':
        shape = 'A'
    elif block[-1].strip().rstrip('%').strip() == r'\end{tabular}':
        shape = 'B'
    else:
        sys.exit(f"generator's last line is neither a bare '}}' nor \\end{{tabular}} "
                 f"({block[-1]!r}); cannot determine the block's extent")

    lines = open(tex).read().split('\n')
    starts = [n for n, l in enumerate(lines) if marker in l and l.lstrip().startswith('%')]
    if len(starts) != 1:
        sys.exit(f"expected exactly 1 marker line matching {marker!r}, found {len(starts)}")
    s = starts[0]

    endtab = next((n for n in range(s, len(lines))
                   if lines[n].strip().rstrip('%').strip() == r'\end{tabular}'), None)
    if endtab is None:
        sys.exit(r"no \end{tabular} after the marker")
    if shape == 'A':
        e = next((n for n in range(endtab + 1, len(lines)) if lines[n].strip() == '}'), None)
        if e is None:
            sys.exit(r"no bare '}' closing the \resizebox after \end{tabular}")
    else:
        # shape B: narrow the region to the tabular itself and drop the generator's comment
        # preamble, because the marker line already exists in the file.
        bt = next((n for n in range(s, len(lines))
                   if lines[n].strip().startswith(r'\begin{tabular}')), None)
        if bt is None:
            sys.exit(r"no \begin{tabular} after the marker")
        s, e = bt, endtab
        while block and not block[0].strip().startswith(r'\begin{tabular}'):
            block.pop(0)
        if not block:
            sys.exit(r"generator emitted no \begin{tabular}")

    # An arm LABEL with a raw `_` is a LaTeX error in a tabular cell, and pdflatex cannot run
    # here, so it would only surface on Overleaf. Caught 2026-09-22: the abl_R label read
    # `routing_norm=none` and had to become `routing\\_norm=none`. The generated block is pure
    # tabular text with no math, so a plain scan is exact here (unlike on the whole document,
    # where inline math spanning two lines gives false positives).
    for i, bl in enumerate(block):
        if bl.lstrip().startswith('%'):
            continue
        probe = re.sub(r'\\_', '', bl)
        probe = re.sub(r'\$[^$]*\$', '', probe)
        if '_' in probe:
            sys.exit(f"REFUSING: generated line {i+1} has an unescaped '_' (LaTeX error in text "
                     f"mode); escape it in the generator as \\\\_ :\n  {bl.strip()[:110]}")

    region = '\n'.join(lines[s:e+1])
    for guard in (r'\caption', r'\label'):
        if guard in region:
            sys.exit(f"REFUSING: the region to replace (lines {s+1}-{e+1}) contains {guard!r}. "
                     "The generated block must not own the caption or the label.")

    out = '\n'.join(lines[:s] + block + lines[e+1:])
    ok, o, c = balanced(out)
    if not ok:
        sys.exit(f"REFUSING: braces would be unbalanced ({o} open vs {c} close)")
    for env in ('table', 'tabular'):
        if len(re.findall(r'\\begin\{'+env+r'\}', out)) != len(re.findall(r'\\end\{'+env+r'\}', out)):
            sys.exit(f"REFUSING: \\begin/\\end{{{env}}} counts would not match")

    open(tex, 'w').write(out)
    print(f"spliced {len(block)} lines into {os.path.basename(tex)} "
          f"(replaced lines {s+1}-{e+1}); braces {o}/{c}, environments matched")

main()
