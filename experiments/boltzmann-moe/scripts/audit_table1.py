#!/usr/bin/env python3
"""Re-derive EVERY cell of tab:main from source and compare against the .tex.

WHY, separately from gen_table1.py: the generator and the table share code, so regenerating proves
nothing about correctness -- a bug in the generator writes the same wrong number both times. This
reads the .tex that will actually be submitted and recomputes each cell by an INDEPENDENT path:

  Active/Total, FLOPwt  <- energy_ff_paramcount.audit_config on the arm's config
  Avg11                 <- the 11 task scores re-averaged here, from the step-pinned eval JSON,
                           NOT via compute_avg11.py (so a bug there cannot hide)
  lm_loss               <- last `train-lm_loss` in the arm's own training stderr
  WikiPPL / MMLU / GSM8K<- read straight out of the same eval JSON

Run after every splice, before pushing. Exits non-zero on any mismatch.

Usage: python scripts/audit_table1.py [--tex <path>]
"""
import re, os, json, glob, sys, argparse
import yaml
sys.path.insert(0, '/proj/dmfexp/nima/Code/dolomite-engine')
from lm_engine.hf_models.modeling_utils.mlp_blocks.energy_ff_paramcount import audit_config

REPO = '/proj/dmfexp/nima/Code/dolomite-engine'
SEARCH = ['configs/cmix', 'configs/iclr_26/ablations', 'configs/iclr_26/scaling', 'configs/iclr_26']

# (scale, row label as printed) -> config basename. Extend when a row is added to gen_table1.GROUPS.
MAP = {
 ('134M','Hybrid (energy MoE)'):'cmix_134M_hybrid_32B_sparse',
 ('134M','Sandwich (energy MoE)'):'cmix_134M_sandwich_32B_sparse',
 ('134M','Pure recurrent (energy MoE)'):'cmix_134M_pure_32B_sparse',
 ('134M','Switch MoE, FLOP-matched'):'abl_B_134M_6G1x6S',
 ('134M','Dense, iso-total'):'abl_D_134M_6G_dense_isototal',
 ('134M','Dense, iso-active'):'abl_F_134M_6G_dense_isoactive',
 ('400M','Hybrid (energy MoE)'):'cmix_400M_hybrid_sparse',
 ('400M','Sandwich (energy MoE)'):'cmix_400M_sandwich_sparse',
 ('400M','Deep, no recurrence (energy MoE)'):'abl_H_400M_6G6E_deep',
 ('400M','Switch MoE, FLOP-matched'):'abl_B_400M_6G1x6S',
 ('400M','Switch MoE, deep'):'abl_H_400M_6G6S_deep',
 ('400M','Dense, iso-active'):'abl_H_400M_6G6G_deep_isoactive',
 ('1B','Stacked 8G4E (energy MoE)'):'cmix1B_12L_gptDense_32B',
}
AN = ['arc_challenge','arc_easy','hellaswag','openbookqa','piqa','sciq']
AC = ['boolq','copa','winogrande','race','lambada_openai']

def cfgpath(a):
    for d in SEARCH:
        p = os.path.join(REPO, d, a + '.yml')
        if os.path.exists(p): return p
    return None

def num(t):
    return float(t.replace('$\\mathbf{','').replace('}$','').replace('$','').rstrip('M'))

ap = argparse.ArgumentParser()
ap.add_argument('--tex', default=os.path.expanduser('~/Code/overleaf/boltzmann-moe-ICLR-2026/sec/experiments.tex'))
a = ap.parse_args()
s = open(a.tex).read()
i = s.find('% GENERATED by experiments/boltzmann-moe/scripts/gen_table1.py')
if i < 0: sys.exit('no gen_table1 marker in ' + a.tex)
body = s[i:s.find('\\end{tabular}', i)]

scale = None; bad = []; n = 0
for line in body.split('\n'):
    m = re.search(r'multicolumn\{\d+\}\{l\}\{\\emph\{(\w+)\}\}', line)
    if m: scale = m.group(1); continue
    if '&' not in line or 'Architecture' in line: continue
    c = [x.strip() for x in line.rstrip('\\\\ ').split('&')]
    if len(c) < 10: continue
    lab = c[0].replace(' $\\dagger$','').strip()
    cfg = MAP.get((scale, lab))
    if not cfg:
        bad.append((scale, lab, 'UNMAPPED ROW -- add it to MAP', '', '')); continue
    p = cfgpath(cfg)
    r = audit_config(p); y = yaml.safe_load(open(p))
    sp = y['save_args']['save_path']; tot = y['training_parameters']['num_training_steps']
    lml = None
    for e in sorted(glob.glob(os.path.expanduser(f'~/bsub_logs/{cfg}_*.stderr')), key=os.path.getmtime, reverse=True):
        if os.path.basename(e).startswith(('ev_','evg_')): continue
        v = re.findall(r'train-lm_loss = ([0-9.]+)', open(e, errors='ignore').read())
        if v: lml = float(v[-1]); break
    d = f'{sp}/unsharded_step{tot}'
    fs = sorted(glob.glob(d+'/harness_results_merged_*.json') + glob.glob(d+'/harness_results_2*.json'),
                key=os.path.getmtime)
    if not fs:
        bad.append((scale, lab, 'NO step-pinned eval', d, '')); continue
    res = json.load(open(fs[-1]))['results']
    def g(t, *ks):
        dd = res.get(t) or {}
        for k in ks:
            for kk, v in dd.items():
                if kk == k or kk.startswith(k+','): return v
        return None
    vals = [g(t,'acc_norm') for t in AN] + [g(t,'acc') for t in AC]
    n += 1
    checks = [
        ('Act/Tot', c[3], f"{r.active/1e6:.0f}M/{r.total/1e6:.0f}M", None),
        ('FLOPwt',  c[4], r.flop_weight/1e6, 0.06),
        ('lm_loss', c[5], lml, 0.00006),
        ('Avg11',   c[6], (100*sum(vals)/len(vals)) if all(v is not None for v in vals) else None, 0.006),
        ('WikiPPL', c[7], g('wikitext','word_perplexity'), 0.006),
        ('MMLU',    c[8], (lambda v: v*100 if v is not None else None)(g('mmlu','acc')), 0.006),
        ('GSM8K',   c[9], (lambda v: v*100 if v is not None else None)(g('gsm8k_cot','exact_match,flexible-extract','exact_match')), 0.006),
    ]
    for name, tex, src, tol in checks:
        if src is None: bad.append((scale, lab, name, tex, 'COULD NOT DERIVE')); continue
        if tol is None:
            if tex != src: bad.append((scale, lab, name, tex, src))
        else:
            try: tv = num(tex)
            except Exception: bad.append((scale, lab, name, tex, 'UNPARSED')); continue
            if abs(tv - src) > tol: bad.append((scale, lab, name, tex, f"{src:.4f}"))

print(f"  rows re-derived: {n}   mismatches: {len(bad)}")
for b in bad: print(f"   *** {b[0]} {b[1]}: {b[2]}  tex={b[3]!r}  source={b[4]!r}")
print("  ==> tab:main VERIFIED AGAINST SOURCE" if not bad else "  ==> DO NOT PUSH until resolved")
sys.exit(1 if bad else 0)
